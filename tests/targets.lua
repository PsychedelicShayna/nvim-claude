-- Run with nvim --headless -u NONE -l tests/targets.lua.
local root = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':h:h')
vim.opt.runtimepath:append(root)
local targets = require('nvim-claude.targets')
local buf = vim.api.nvim_get_current_buf()
local function lines(value)
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, value)
end
local function current()
  return vim.api.nvim_buf_get_lines(buf, 0, -1, false)
end
local function apply(selected, replacements)
  return targets.apply(buf, selected, replacements, function(value) return value end)
end
lines({ 'alpha café' })
local live
vim.keymap.set('x', 'gR', function() live = targets.selection(buf) end)
vim.api.nvim_win_set_cursor(0, { 1, 0 })
vim.api.nvim_feedkeys('v4lgR', 'mxt', false)
assert(live and targets.wire(buf, live)[1].text == 'alpha')
vim.cmd('normal! \27')
vim.keymap.del('x', 'gR')

lines({ 'café z' })
vim.api.nvim_win_set_cursor(0, { 1, 6 })
vim.cmd('normal! v3h\27')
local reversed = assert(targets.selection(buf))
local span = targets.wire(buf, reversed)[1]
assert(span.text == 'fé z' and span.before == 'ca' and span.after == '')
assert(apply(reversed, { { id = 'target-0', text = 'lion' } }))
assert(current()[1] == 'calion')
vim.cmd('undo')
assert(current()[1] == 'café z')

lines({ 'first', 'replace me', 'last' })
vim.api.nvim_win_set_cursor(0, { 2, 0 })
vim.cmd('normal! v9l\27')
local moving = assert(targets.selection(buf))
vim.api.nvim_buf_set_lines(buf, 0, 0, false, { 'new' })
assert(targets.valid(buf, moving))
assert(apply(moving, { { id = 'target-0', text = 'done' } }))
assert(current()[3] == 'done')
vim.api.nvim_buf_set_text(buf, 2, 0, 2, 4, { 'changed' })
assert(not targets.valid(buf, moving))
assert(not apply(moving, { { id = 'target-0', text = 'overwrite' } }))
assert(current()[3] == 'changed')

lines({ 'a\txyz', 'é\tqwer', 'k\tend' })
vim.api.nvim_win_set_cursor(0, { 1, 1 })
vim.cmd('normal! \22j2l\27')
local block = assert(targets.selection(buf))
local selected = targets.wire(buf, block)
assert(#selected == 2 and selected[1].text == ' xy' and selected[2].text == ' qw')
assert(not apply(block, { { id = 'target-0', text = 'Z\nnew' }, { id = 'target-1', text = 'Q' } }))
assert(current()[1] == 'a\txyz')
assert(apply(block, { { id = 'target-0', text = 'Z' }, { id = 'target-1', text = 'Q' } }))
assert(current()[1] == 'a      Zz' and current()[2] == 'é      Qer')
vim.cmd('undo')
assert(current()[1] == 'a\txyz' and current()[2] == 'é\tqwer')

lines({ 'wxyz', 'x', 'tail' })
vim.api.nvim_win_set_cursor(0, { 1, 2 })
vim.cmd('normal! \22j1l\27')
local short = assert(targets.selection(buf))
assert(#short == 2 and targets.wire(buf, short)[2].text == '')
assert(apply(short, { { id = 'target-0', text = 'A' }, { id = 'target-1', text = 'B' } }))
assert(current()[1] == 'wAz' and current()[2] == 'xB' and current()[3] == 'tail')

lines({ 'brown fox' })
vim.api.nvim_win_set_cursor(0, { 1, 0 })
local insertion = targets.insertion(buf, false)
local boundary = targets.wire(buf, insertion)[1]
assert(boundary.before == '' and boundary.after == 'brown fox')
assert(apply(insertion, { { id = 'target-0', text = 'quick ' } }))
assert(current()[1] == 'quick brown fox')
vim.cmd('undo')
assert(current()[1] == 'brown fox')
print('target selections, stale edits, block cells, and undo: PASS')
