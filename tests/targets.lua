vim.opt.rtp:prepend(vim.fn.getcwd())
local t = require('nvim-claude.targets')
local a = vim.api
local function buffer(lines)
  vim.cmd('enew!')
  a.nvim_buf_set_lines(0, 0, -1, false, lines)
  vim.bo.undolevels = vim.bo.undolevels
end
local function select(keys)
  vim.cmd('normal! ' .. keys)
  return t.capture('replace', true)
end
local function replace(g, texts)
  local out = {}
  for i, seg in ipairs(g.segments) do out[i] = { id = seg.id, text = texts[i] } end
  t.apply(g, out)
end
buffer({'The ... brown fox.'})
a.nvim_win_set_cursor(0, {1,4})
local g = select('v2l')
assert(t.encode(g)[1].text == '...')
replace(g, {'quick'})
assert(a.nvim_get_current_line() == 'The quick brown fox.')
assert(t.valid(g) and t.encode(g)[1].text == 'quick')
replace(g, {'slow'})
assert(a.nvim_get_current_line() == 'The slow brown fox.')
vim.cmd('undo')
assert(a.nvim_get_current_line() == 'The quick brown fox.')
assert(not t.valid(g), 'undo must invalidate the remembered replacement')
buffer({'αβγ xyz'})
a.nvim_win_set_cursor(0, {1,4})
g = select('vh')
assert(t.encode(g)[1].text == 'βγ')
replace(g, {'é'})
assert(a.nvim_get_current_line() == 'αé xyz')
buffer({'one', 'two', 'three'})
a.nvim_win_set_cursor(0, {2,0})
g = select('V')
replace(g, {'TWO'})
assert(vim.deep_equal(a.nvim_buf_get_lines(0,0,-1,false), {'one','TWO','three'}))
buffer({'one target suffix'})
a.nvim_win_set_cursor(0,{1,4})
g = select('v5l')
a.nvim_buf_set_text(0,0,0,0,0,{'prefix '})
assert(t.valid(g))
replace(g, {'new'})
assert(a.nvim_get_current_line() == 'prefix one new suffix')
a.nvim_buf_set_text(0,0,11,0,12,{'X'})
assert(not t.valid(g))
buffer({'hello'})
a.nvim_win_set_cursor(0,{1,2})
g = t.capture('generate')
replace(g, {'  world\n'})
assert(vim.deep_equal(a.nvim_buf_get_lines(0,0,-1,false), {'he  world','llo'}))
buffer({'abcd', 'efgh'})
a.nvim_win_set_cursor(0,{1,1})
g = select('\22jl')
assert(#g.segments == 2)
replace(g, {'X','Y'})
assert(vim.deep_equal(a.nvim_buf_get_lines(0,0,-1,false), {'aXd','eYh'}))
vim.cmd('undo')
assert(vim.deep_equal(a.nvim_buf_get_lines(0,0,-1,false), {'abcd','efgh'}))
buffer({'\tabc', '12345678Z'})
vim.bo.tabstop = 8
vim.o.virtualedit = 'block'
a.nvim_win_set_cursor(0,{2,2})
g = select('\22k2l')
replace(g, {'X','Y'})
assert(vim.deep_equal(a.nvim_buf_get_lines(0,0,-1,false), {'  X   abc','12Y678Z'}), vim.inspect(a.nvim_buf_get_lines(0,0,-1,false)))
print('target behavior: passed')
vim.cmd('qa!')
