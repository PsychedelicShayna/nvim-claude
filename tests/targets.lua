vim.opt.runtimepath:append(vim.fn.getcwd())
local target = require('nvim-claude.target')
local buf = vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_lines(buf, 0, -1, false, { 'before café after', 'untouched' })
vim.api.nvim_win_set_cursor(0, { 1, 7 })
local capture = assert(target.capture('generate', false, false))
assert(capture.targets[1].start[2] == 7)
assert(target.apply(capture, { { id = capture.targets[1].id, text = 'NEW ' } }))
assert(vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1] == 'before NEW café after')
local previous = assert(target.capture('replace', false, false))
assert(target.valid(previous))
vim.api.nvim_buf_set_text(buf, 0, 0, 0, 0, { 'X' })
assert(target.valid(previous))
vim.api.nvim_buf_set_text(buf, 0, 9, 0, 10, { 'Z' })
assert(not target.valid(previous))
print('target extmark movement and stale edit checks passed')
