vim.opt.runtimepath:append(vim.fn.getcwd())
local target = require('nvim-claude.target')
local buf = vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_lines(buf, 0, -1, false, { 'a café z', 'x\tZ' })
vim.api.nvim_win_set_cursor(0, { 1, 2 })
vim.cmd('normal! v2l')
vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes('<Esc>', true, false, true), 'x', false)
local capture = assert(target.capture('replace', true, false))
assert(capture.targets[1].text == 'caf', vim.inspect(capture.targets))
local remembered = assert(target.capture('replace', false, false))
assert(remembered.targets[1].text == 'caf')
assert(target.apply(capture, { { id = capture.targets[1].id, text = 'tea' } }))
assert(vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1] == 'a teaé z')
local followup = assert(target.capture('replace', false, false))
assert(followup.targets[1].text == 'tea')
vim.o.selection = 'exclusive'
vim.api.nvim_buf_set_lines(buf, 0, -1, false, { 'hello world' })
vim.api.nvim_win_set_cursor(0, { 1, 0 })
vim.cmd('normal! v4l')
vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes('<Esc>', true, false, true), 'x', false)
local exclusive = assert(target.capture('replace', true, false))
assert(exclusive.targets[1].text == 'hell', vim.inspect(exclusive.targets))
vim.o.selection = 'inclusive'
print('visual selection replacement passed')
