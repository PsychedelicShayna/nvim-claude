vim.opt.runtimepath:append(vim.fn.getcwd())
vim.g.mapleader = '\\'
local plugin = require('nvim-claude')
plugin.setup({})
assert(vim.fn.exists(':NvClaude') == 2)
assert(vim.fn.maparg('\\cc', 'n') ~= '')
assert(vim.fn.maparg('\\ca', 'x') ~= '')
assert(vim.fn.maparg('\\ci', 'i') == '')
plugin.setup({ keys = { ask = '<leader>z', generate = false } })
assert(vim.fn.maparg('\\z', 'n') ~= '')
assert(vim.fn.maparg('\\ca', 'n') == '')
assert(vim.fn.maparg('\\ci', 'n') == '')
plugin.setup({ keys = false })
assert(vim.fn.exists(':NvClaude') == 2)
assert(vim.fn.maparg('\\z', 'n') == '')
assert(vim.fn.maparg('\\cc', 'n') == '')
print('setup mapping overrides and disabling passed')
