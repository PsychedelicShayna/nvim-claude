vim.opt.runtimepath:append(vim.fn.getcwd())
local ui = require('nvim-claude.ui')
local origin = vim.api.nvim_get_current_win()
local update = ui.answer('Answer', origin)
local buf = vim.api.nvim_get_current_buf()
update('streaming')
vim.api.nvim_feedkeys('q', 'x', false)
assert(vim.api.nvim_get_current_win() == origin)
update('finished after close')
ui.show_last()
assert(vim.api.nvim_get_current_buf() == buf)
assert(vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1] == 'finished after close')
print('closed response retains final text and reopens')
